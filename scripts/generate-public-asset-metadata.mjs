import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const projectRoot = process.cwd();
const publicRoot = path.join(projectRoot, "public");
const outputPath = path.join(
  projectRoot,
  "src",
  "data",
  "public-asset-metadata.ts",
);
const imageExtensions = new Set([
  ".avif",
  ".gif",
  ".jpeg",
  ".jpg",
  ".png",
  ".webp",
]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(absolute)));
    else if (entry.isFile()) files.push(absolute);
  }
  return files;
}

const rows = [];
for (const absolute of await walk(publicRoot)) {
  const extension = path.extname(absolute).toLowerCase();
  if (!imageExtensions.has(extension)) continue;
  const metadata = await sharp(absolute, { animated: true }).metadata();
  if (!metadata.width || !metadata.height) continue;
  const relative = path.relative(publicRoot, absolute).split(path.sep).join("/");
  rows.push({
    path: `/${relative}`,
    width: metadata.width,
    height: metadata.height,
    format: metadata.format ?? extension.slice(1),
  });
}

rows.sort((left, right) => left.path.localeCompare(right.path));
const body = `/**\n * AUTO-GENERATED by scripts/generate-public-asset-metadata.mjs.\n * Every image currently shipped from public/ is measured with Sharp.\n */\nexport type PublicAssetMetadata = Readonly<{\n  width: number;\n  height: number;\n  format: string;\n}>;\n\nexport const PUBLIC_ASSET_METADATA: Readonly<Record<string, PublicAssetMetadata>> = ${JSON.stringify(
  Object.fromEntries(
    rows.map((row) => [
      row.path,
      { width: row.width, height: row.height, format: row.format },
    ]),
  ),
  null,
  2,
)} as const;\n`;

await writeFile(outputPath, body, "utf8");
console.log(`Wrote ${rows.length} measured public assets to ${outputPath}`);
