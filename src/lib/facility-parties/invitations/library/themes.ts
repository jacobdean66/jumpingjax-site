const BASE = "/invitation-library";

function fluent(
  folder: string,
  file: string,
  alt: string,
): InvitationLibraryAsset {
  return {
    id: file.replace(/\.png$/, ""),
    src: `${BASE}/${folder}/${file}`,
    alt,
    licenseId: "fluent-emoji",
  };
}

