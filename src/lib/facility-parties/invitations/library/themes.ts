export const INVITATION_LIBRARY_BY_ID = new Map(
  INVITATION_LIBRARY_THEMES.map((theme) => [theme.id, theme]),
);

export function getInvitationLibraryTheme(
  id: string,
): InvitationLibraryTheme {
  return (
    INVITATION_LIBRARY_BY_ID.get(id as InvitationLibraryTheme["id"]) ??
    INVITATION_LIBRARY_BY_ID.get("classic-birthday")!
  );
}
