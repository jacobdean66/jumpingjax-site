function pal(
  id: string,
  background: string,
  backgroundAlt: string,
  accent: string,
  text: string,
): InvitationLibraryPalette {
  const muted = text.toLowerCase() === "#ffffff" || text.toLowerCase() === "#f8fafc" || text.toLowerCase() === "#fff7ed" || text.toLowerCase() === "#ecfccb" || text.toLowerCase() === "#e2e8f0" || text.toLowerCase() === "#dbeafe" || text.toLowerCase() === "#ecfeff" || text.toLowerCase() === "#fffbeb" || text.toLowerCase() === "#fee2e2"
    ? text
    : "#334155";
  return {
    id,
    background,
    backgroundAlt,
    accent,
    accent2: backgroundAlt,
    text,
    muted,
    border: accent,
  };
}

